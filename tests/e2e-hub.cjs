// Start menu search, Reminders, Pantry and Warranties browser test.
const { chromium } = require('playwright');
const path = require('path');
const BASE = process.env.BASE || 'http://127.0.0.1:8080/';
const SHOTS = process.argv[2] || '';
let failures = 0;
const check = (c, m) => { console.log(`${c ? '✓' : '✗'} ${m}`); if (!c) failures++; };

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const shot = (n, p = page) => SHOTS && p.screenshot({ path: path.join(SHOTS, n + '.png') });
  let lookups = 0;
  await page.route(/openfoodfacts/, (r) => { lookups++; return r.fulfill({ contentType: 'application/json', body: JSON.stringify(r.request().url().includes('3017620422003') ? { status: 1, product: { product_name: 'Nutella', brands: 'Ferrero', quantity: '400 g' } } : { status: 0 }) }); });
  await page.route(/upcitemdb|googleapis|openlibrary/, (r) => r.fulfill({ status: 404, body: '{}' }));

  await page.goto(BASE + '?nosw#/');
  await page.waitForSelector('[data-gq]');
  const DAY = 86400000;
  const iso = (ms) => { const d = new Date(ms); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; };
  await page.evaluate(async ({ DAY, lent, soon }) => {
    const s = await import('./js/core/store.js');
    await s.put('rooms', { id: 'garage', name: 'Garage', order: 9, areas: [{ id: 'shelf', name: 'Metal shelving', kind: 'shelf', spots: [{ id: 'bx', name: 'Box 4' }] }] });
    await s.put('books', { id: 'b1', title: 'The Hobbit', authors: ['J. R. R. Tolkien'], isbn13: '9780261103344', lentTo: 'Sam', lentDate: lent, addedAt: Date.now() });
    await s.put('books', { id: 'b2', title: 'Birdsong', authors: ['Sebastian Faulks'], addedAt: Date.now() });
    await s.put('items', { id: 'i1', name: 'Cordless drill', brand: 'Bosch', barcode: '4053423201234', location: { roomId: 'garage', areaId: 'shelf', spotId: 'bx' } });
    await s.put('teams', { id: 't1', name: 'Frontage RFC', sport: 'rugby', mine: true });
    await s.put('players', { id: 'p1', name: 'Hobbs Taylor', teamIds: ['t1'] });
    await s.put('matches', { id: 'm1', sport: 'rugby', teamId: 't1', oppName: 'Riverside', title: 'Frontage RFC v Riverside', date: soon, venue: 'Home ground', status: 'upcoming' });
  }, { DAY, lent: iso(Date.now() - 45 * DAY), soon: iso(Date.now() + 2 * DAY) });

  // ---- Global search ----
  await page.goto(BASE + '?nosw#/');
  await page.keyboard.press('/');
  check(await page.evaluate(() => document.activeElement?.matches('[data-gq]')), '“/” jumps to the search box');
  await page.keyboard.type('hobbit');
  await page.waitForSelector('.gs-hit');
  const groups = await page.$$eval('.gs-group h2', (els) => els.map((e) => e.textContent.replace(/\s+/g, ' ').trim()));
  check(groups[0].startsWith('📚 Library'), `best match first: Library (${groups.join(' | ')})`);
  check(await page.isHidden('[data-menu-body]'), 'tool tiles hidden while searching');
  check((await page.innerHTML('.gs-hit >> nth=0')).includes('<mark>Hobbit</mark>'), 'matching text highlighted');
  await shot('hub-search');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await page.waitForSelector('h1:has-text("The Hobbit")');
  check(true, 'keyboard: ↓ then Enter opens the book');
  await page.goBack();
  await page.waitForSelector('.gs-hit');
  check((await page.inputValue('[data-gq]')) === 'hobbit', 'Back returns to the same results');
  await page.fill('[data-gq]', 'hobb');
  await page.waitForFunction(() => document.querySelectorAll('.gs-group').length === 2);
  check(true, 'part of a word finds both the book and the player Hobbs Taylor');
  await page.fill('[data-gq]', '4053423201234');
  await page.waitForSelector('.gs-hit:has-text("Cordless drill")');
  check((await page.textContent('.gs-hit:has-text("Cordless drill")')).includes('Garage › Metal shelving › Box 4'), 'barcode finds the item and shows where it is');
  await page.fill('[data-gq]', 'box 4');
  await page.waitForSelector('.gs-hit:has-text("Box 4")');
  check(true, 'places (rooms, shelves, boxes) are searchable');
  await page.fill('[data-gq]', 'riverside');
  await page.waitForSelector('.gs-hit:has-text("Frontage RFC v Riverside")');
  check(true, 'matches are searchable');
  await page.fill('[data-gq]', 'zzqx');
  await page.waitForSelector('text=Nothing found');
  check(true, 'friendly “nothing found”');
  await page.press('[data-gq]', 'Escape');
  await page.waitForSelector('[data-menu-body]:not([hidden]) .menu-grid');
  check(true, 'Esc clears the search and brings back the tools');
  // Live: a book added while results are showing appears without retyping
  await page.fill('[data-gq]', 'silmarillion');
  await page.waitForSelector('text=Nothing found');
  await page.evaluate(async () => (await import('./js/core/store.js')).put('books', { id: 'b3', title: 'The Silmarillion', authors: ['J. R. R. Tolkien'] }));
  await page.waitForSelector('.gs-hit:has-text("The Silmarillion")');
  check(true, 'results update live when something new arrives');
  await page.fill('[data-gq]', '');

  // ---- Reminders ----
  await page.goto(BASE + '?nosw#/');
  await page.waitForSelector('.rem-card');
  const card = (await page.textContent('.rem-card')).replace(/\s+/g, ' ');
  check(/2 reminders · 1 needs attention/.test(card) && card.includes('The Hobbit — lent to Sam'), `start menu reminder card: ${card.trim()}`);
  await page.click('.rem-card');
  await page.waitForSelector('.rem');
  const rems = await page.$$eval('.rem .row-title', (els) => els.map((e) => e.textContent));
  check(rems.length === 2 && rems[0].includes('The Hobbit') && rems[1].includes('Frontage RFC v Riverside'), `reminders screen: ${rems.join(' | ')}`);
  check((await page.textContent('.rem >> nth=0')).includes('45 days ago'), 'lent 45 days ago');
  check((await page.textContent('.rem >> nth=1')).includes('in 2 days · Home ground'), 'match in 2 days at Home ground');
  await shot('hub-reminders');
  await page.click('[data-snooze^="lent:book:b1"]');
  await page.waitForFunction(() => document.querySelectorAll('.rem').length === 1);
  check(true, 'hide for 7 days');
  await page.click('.toast button:has-text("Undo")');
  await page.waitForFunction(() => document.querySelectorAll('.rem').length === 2);
  check(true, 'undo brings it back');
  // Giving the book back clears the reminder everywhere
  await page.evaluate(async () => (await import('./js/core/store.js')).patch('books', 'b1', { lentTo: '', lentDate: '' }));
  await page.waitForFunction(() => document.querySelectorAll('.rem').length === 1);
  check(true, 'returning the book removes its reminder live');

  // ---- Pantry ----
  await page.goto(BASE + '?nosw#/pantry/add');
  await page.fill('[data-manual] input', '3017620422003');
  await page.press('[data-manual] input', 'Enter');
  await page.waitForSelector('.sheet [name=name]');
  check((await page.inputValue('.sheet [name=name]')) === 'Nutella 400 g' && (await page.inputValue('.sheet [name=brand]')) === 'Ferrero', 'barcode looked up with Inventory’s food lookup');
  await page.click('.sheet [data-days="7"]');
  await page.click('.sheet button.btn-primary');
  await page.waitForSelector('.toast >> text=Added Nutella 400 g');
  // Same product again: filled in from memory, no lookup, usual date suggested
  const before = lookups;
  await page.waitForTimeout(3100); // same-code repeat guard
  await page.fill('[data-manual] input', '3017620422003');
  await page.press('[data-manual] input', 'Enter');
  await page.waitForSelector('.sheet [name=name]');
  const remembered = await page.evaluate(() => ({ name: document.querySelector('.sheet [name=name]').value, exp: document.querySelector('.sheet [name=expiry]').value, note: document.querySelector('.sheet').textContent }));
  check(lookups === before && remembered.name === 'Nutella 400 g' && remembered.exp && remembered.note.includes('usually lasts 7 days') && remembered.note.includes('You already have 1'), 'known product fills in instantly with its usual date (no internet needed)');
  await page.click('.sheet [data-close]');
  await page.click('[data-nocode]');
  await page.fill('.sheet [name=name]', 'Milk');
  await page.click('.sheet [data-st="fridge"]');
  await page.click('.sheet [data-days="3"]');
  await page.click('.sheet button.btn-primary');
  await page.waitForSelector('.toast >> text=Added Milk');
  await page.evaluate(async () => {
    const s = await import('./js/core/store.js');
    const d = new Date(Date.now() - 86400000);
    await s.put('pantry', { id: 'ham', name: 'Ham', storage: 'fridge', quantity: 1, expiry: `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`, addedAt: Date.now() });
  });
  await page.goto(BASE + '?nosw#/pantry');
  await page.waitForSelector('.pantry-group');
  const pg = await page.$$eval('.pantry-group', (els) => els.map((e) => e.querySelector('.section-title').textContent.replace(/\s+\d+$/, '').trim() + ': ' + [...e.querySelectorAll('.row-title')].map((t) => t.textContent.trim()).join(',')));
  check(pg.join(' | ') === 'Past its date: Ham | Use in the next 3 days: Milk | This week: Nutella 400 g', `grouped by date: ${pg.join(' | ')}`);
  await shot('hub-pantry');
  await page.click('.pantry-row:has(.row-title:text-is("Milk")) [data-use]');
  await page.click('.toast button:has-text("Add to shopping list")');
  await page.waitForSelector('.toast >> text=Milk added to the shopping list');
  check(!(await page.$('.row-title:text-is("Milk")')), 'used the last milk: gone from the pantry, on the shopping list');
  await page.click('[data-filter="fridge"]');
  check((await page.$$('.pantry-row')).length === 1, 'filter by fridge');
  await page.click('[data-filter="all"]');
  await page.goto(BASE + '?nosw#/pantry/shopping');
  await page.fill('[data-add] input', 'Eggs');
  await page.press('[data-add] input', 'Enter');
  await page.waitForSelector('.shop-item:has-text("Eggs")');
  check((await page.$$eval('.shop-item', (els) => els.map((e) => e.textContent.trim()))).join(',').replace(/\s+/g, '') === 'Eggs,Milk', 'shopping list: Eggs and Milk');
  await page.check('.shop-item:has-text("Eggs") input');
  await page.click('[data-putaway]');
  await page.click('.sheet [data-ok]');
  await page.waitForFunction(() => document.querySelectorAll('.shop-item').length === 1);
  check(await page.evaluate(async () => (await import('./js/core/store.js')).all('pantry').some((f) => f.name === 'Eggs')), 'ticked Eggs put into the pantry and taken off the list');
  // Buying milk again takes it off the list automatically
  await page.goto(BASE + '?nosw#/pantry/add');
  await page.click('[data-nocode]');
  await page.fill('.sheet [name=name]', 'milk');
  await page.click('.sheet button.btn-primary');
  await page.waitForSelector('.toast >> text=Added milk');
  check(await page.evaluate(async () => (await import('./js/core/store.js')).all('shopping').length === 0), 'scanning milk into the pantry ticks it off the shopping list');
  await page.goto(BASE + '?nosw#/');
  await page.waitForSelector('.rem-card');
  check((await page.textContent('.rem-card')).includes('Ham'), 'out-of-date ham shows on the start menu reminders');
  await page.fill('[data-gq]', 'nutella');
  await page.waitForSelector('.gs-group:has-text("Pantry") .gs-hit');
  check(true, 'pantry is searchable from the start menu');
  await page.fill('[data-gq]', '');

  // ---- Warranties & documents ----
  await page.goto(BASE + '?nosw#/inventory/item/i1');
  await page.click('a:has-text("Add warranty or receipt")');
  await page.waitForSelector('.doc-form');
  check((await page.inputValue('.doc-form [name=title]')) === 'Cordless drill' && (await page.inputValue('.doc-form [name=itemId]')) === 'i1', 'started from the item: title and link filled in');
  check(await page.isVisible('.doc-form [data-box] [data-spot="bx"][aria-pressed="true"]'), 'box location starts at where the item lives (Garage › Metal shelving › Box 4)');
  const bought = iso(Date.now() - 710 * DAY);
  await page.fill('.doc-form [name=purchaseDate]', bought);
  await page.click('.doc-form [data-months="24"]');
  const ends = await page.inputValue('.doc-form [name=expiry]');
  check(ends > iso(Date.now()) && ends < iso(Date.now() + 30 * DAY), `“2 years from purchase” sets the end date (${ends})`);
  await page.fill('.doc-form [name=seller]', 'Toolstation');
  await page.setInputFiles('.doc-form [data-photo][multiple]', [path.join(__dirname, 'fixtures/photos/IMG_0101.JPG'), path.join(__dirname, 'fixtures/photos/IMG_0102.JPG')]);
  await page.waitForFunction(() => document.querySelectorAll('.doc-form .doc-img').length === 2);
  await page.click('.doc-form button.btn-primary');
  await page.waitForSelector('.doc-status');
  const docText = await page.textContent('#view');
  check(docText.includes('left') && docText.includes('Cordless drill') && docText.includes('Garage') && docText.includes('Box 4') && docText.includes('Toolstation'), 'document page: time left, linked item, where the box is, shop');
  const img = await page.evaluate(async () => { const s = await import('./js/core/store.js'); const i = s.all('docImages'); return { n: i.length, kb: Math.round(Math.max(...i.map((x) => x.data.length)) / 1024) }; });
  check(img.n === 2 && img.kb < 400, `2 receipt photos saved separately, small enough to sync (${img.kb} KB)`);
  await page.click('.doc-img >> nth=0');
  await page.waitForSelector('.sheet .doc-full');
  check(true, 'photo opens full size');
  await shot('hub-warranty');
  await page.keyboard.press('Escape');
  await page.click('.sheet [data-close]').catch(() => {});
  await page.goto(BASE + '?nosw#/inventory/item/i1');
  await page.waitForSelector('.list-item:has-text("Cordless drill")');
  check((await page.textContent('#view')).includes('Until'), 'the item page shows its warranty');
  await page.goto(BASE + '?nosw#/warranties');
  await page.waitForSelector('.doc-group');
  check((await page.textContent('.doc-group.g-soon')).includes('Cordless drill'), 'listed under “Running out soon”');
  // Edit: remove one photo
  await page.click('.doc-group .row');
  await page.click('a:has-text("Edit")');
  await page.waitForSelector('.doc-form .doc-img');
  await page.click('.doc-form [data-rm="1"]');
  await page.click('.doc-form button.btn-primary');
  await page.waitForSelector('.doc-status');
  check(await page.evaluate(async () => (await import('./js/core/store.js')).all('docImages').length === 1), 'removing a photo while editing deletes it');
  // Delete + undo brings photos back too
  await page.click('[data-del]');
  await page.click('.sheet [data-ok]');
  await page.waitForSelector('.toast button:has-text("Undo")');
  await page.click('.toast button:has-text("Undo")');
  await page.waitForFunction(async () => { const s = await import('./js/core/store.js'); return s.all('docs').length === 1 && s.all('docImages').length === 1; });
  check(true, 'delete → undo restores the document and its photo');
  await page.goto(BASE + '?nosw#/');
  await page.waitForSelector('.rem-card');
  await page.click('.rem-card');
  await page.waitForSelector('.rem');
  check((await page.textContent('#view')).includes('Cordless drill') && (await page.textContent('#view')).includes('Runs out'), 'warranty running out shows in Reminders');
  await page.goto(BASE + '?nosw#/');
  await page.fill('[data-gq]', 'toolstation');
  await page.waitForSelector('.gs-group:has-text("Warranties") .gs-hit');
  check(true, 'documents searchable by shop');
  await page.fill('[data-gq]', '');

  check(!errors.length, 'no JavaScript errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
  await browser.close();
  console.log(failures ? `\n${failures} FAILED` : '\nAll hub checks passed');
  process.exit(failures ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
